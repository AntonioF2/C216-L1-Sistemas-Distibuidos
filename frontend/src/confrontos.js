export const TOTAL_RODADAS = confrontosPorRodada.length;

const idPorSigla = new Map(times.map(({ id, sigla }) => [sigla, id]));

export function confrontosDaRodada(rodada) {
  const confrontos = confrontosPorRodada[rodada - 1];
  return confrontos.map(([mandante, visitante], indice) => ({
    id: (rodada - 1) * confrontos.length + indice + 1,
    rodada,
    mandante_id: idPorSigla.get(mandante),
    visitante_id: idPorSigla.get(visitante),
  }));
}
